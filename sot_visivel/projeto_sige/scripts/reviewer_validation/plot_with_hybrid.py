#!/usr/bin/env python3
"""Plot new tracker results together with the final hybrid reported in the paper.

The hybrid point estimates are intentionally marked as historical/article-reported
because they were not regenerated by the new common evaluator in this step.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd


ARTICLE_HYBRID = {
    "method": "Híbrido final\n(Damped + MOG2)",
    "SR@0.5": 0.863,
    "H15": 58.17,
    "H30": 106.14,
    "FPS": 29.8,
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", type=Path, default=Path("scripts/reviewer_validation/results_with_deepsort/summary_mean_std_ci95.csv"))
    parser.add_argument("--output-dir", type=Path, default=Path("scripts/reviewer_validation/results_with_deepsort/figures"))
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    summary = pd.read_csv(args.summary)
    methods = ["BoT-SORT_YOLO26n", "BoT-SORT_ajustado_n", "DeepSORT", "ByteTrack"]
    labels = {
        "BoT-SORT_YOLO26n": "BoT-SORT padrão",
        "BoT-SORT_ajustado_n": "BoT-SORT ajustado",
        "DeepSORT": "DeepSORT",
        "ByteTrack": "ByteTrack",
        ARTICLE_HYBRID["method"]: ARTICLE_HYBRID["method"],
    }
    colors = ["#64748b", "#94a3b8", "#ef4444", "#3b82f6", "#16a34a"]

    panels = [
        ("SR@0.5", "SR@0,5", "higher", {**{m: float(summary[(summary.method == m) & (summary.metric == "SR@0.5")]["mean"].iloc[0]) for m in methods}, ARTICLE_HYBRID["method"]: ARTICLE_HYBRID["SR@0.5"]}),
        ("H15", "Erro de predição H15 (px)", "lower", {**{m: float(summary[(summary.method == m) & (summary.metric == "pred_error_H15_mean")]["mean"].iloc[0]) for m in methods}, ARTICLE_HYBRID["method"]: ARTICLE_HYBRID["H15"]}),
        ("H30", "Erro de predição H30 (px)", "lower", {**{m: float(summary[(summary.method == m) & (summary.metric == "pred_error_H30_mean")]["mean"].iloc[0]) for m in methods}, ARTICLE_HYBRID["method"]: ARTICLE_HYBRID["H30"]}),
        ("FPS", "FPS médio", "higher", {**{m: float(summary[(summary.method == m) & (summary.metric == "FPS_from_log")]["mean"].iloc[0]) for m in methods}, ARTICLE_HYBRID["method"]: ARTICLE_HYBRID["FPS"]}),
    ]

    fig, axes = plt.subplots(2, 2, figsize=(13, 8.5))
    for ax, (_, ylabel, direction, values) in zip(axes.flat, panels):
        order = methods + [ARTICLE_HYBRID["method"]]
        vals = [values[m] for m in order]
        bars = ax.bar(range(len(order)), vals, color=colors, edgecolor="#1f2937", linewidth=0.5)
        bars[-1].set_hatch("///")
        bars[-1].set_edgecolor("#166534")
        if "H15" in ylabel:
            metric_name = "pred_error_H15_mean"
        elif "H30" in ylabel:
            metric_name = "pred_error_H30_mean"
        elif "SR" in ylabel:
            metric_name = "SR@0.5"
        else:
            metric_name = "FPS_from_log"
        errors = []
        for method in methods:
            row = summary[(summary.method == method) & (summary.metric == metric_name)]
            errors.append(float(row["std_between_sequences"].iloc[0]) if not row.empty and metric_name not in {"SR@0.5", "FPS_from_log"} else 0.0)
        errors.append(0.0)
        # Add error bars only to methods generated by the common evaluator;
        # the article-reported hybrid is intentionally a point estimate.
        ax.errorbar(range(len(order)), vals, yerr=errors, fmt="none", ecolor="#111827", capsize=3, linewidth=1)
        ax.set_xticks(range(len(order)))
        ax.set_xticklabels([labels[m] for m in order], rotation=20, ha="right")
        ax.set_ylabel(ylabel)
        ax.grid(axis="y", alpha=0.25)
        ax.set_axisbelow(True)
        for idx, value in enumerate(vals):
            ax.text(idx, value, f"{value:.3f}" if "SR" in ylabel else f"{value:.1f}", ha="center", va="bottom", fontsize=9)

    fig.suptitle("Comparação com o híbrido final reportado no artigo", fontsize=15)
    fig.text(0.5, 0.01, "Barras coloridas: avaliação comum em 20 sequências. Barra hachurada: valor reportado no artigo; ainda não reavaliado pelo avaliador comum.", ha="center", fontsize=9)
    fig.tight_layout(rect=(0, 0.04, 1, 0.96))
    fig.savefig(args.output_dir / "comparison_with_hybrid_article_reported.png", dpi=240)
    fig.savefig(args.output_dir / "comparison_with_hybrid_article_reported.pdf")
    plt.close(fig)

    source = pd.DataFrame([
        {"method": ARTICLE_HYBRID["method"], "source": "Table II and imagemartigo.py", "SR@0.5": ARTICLE_HYBRID["SR@0.5"], "H15": ARTICLE_HYBRID["H15"], "H30": ARTICLE_HYBRID["H30"], "FPS": ARTICLE_HYBRID["FPS"], "uncertainty": "not available in the published table"}
    ])
    source.to_csv(args.output_dir / "hybrid_article_reported_source.csv", index=False)
    print(f"Saved hybrid comparison figure in {args.output_dir}")


if __name__ == "__main__":
    main()
